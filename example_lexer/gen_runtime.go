//go:build ignore

// Regenerates runtime.elf and rtaddrs_gen.go from runtime.c.
// Usage (inside example_lexer): go run gen_runtime.go
package main

import (
	"debug/elf"
	"fmt"
	"os"
	"os/exec"
	"sort"
	"strings"
)

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func main() {
	args := []string{"-O2", "-std=gnu11", "-w", "-static", "-fcf-protection=none",
		"-fno-asynchronous-unwind-tables", "-fno-stack-protector", "-fomit-frame-pointer",
		"-no-pie", "-Wl,--build-id=none", "-Wl,-z,norelro",
		"-o", "runtime_unstripped.elf", "rt/runtime.c", "-lm"}
	out, err := exec.Command("gcc", args...).CombinedOutput()
	if err != nil {
		fmt.Fprintln(os.Stderr, string(out))
		must(err)
	}
	f, err := elf.Open("runtime_unstripped.elf")
	must(err)
	syms, err := f.Symbols()
	must(err)
	addrs := map[string]uint64{}
	for _, s := range syms {
		if s.Name == "kpj_code" || strings.HasPrefix(s.Name, "_kpj_") || strings.HasPrefix(s.Name, "kpj_") {
			addrs[s.Name] = s.Value
		}
	}
	code := addrs["kpj_code"]
	var off uint64
	found := false
	for _, p := range f.Progs {
		if p.Type == elf.PT_LOAD && code >= p.Vaddr && code+262144 <= p.Vaddr+p.Filesz {
			off = code - p.Vaddr + p.Off
			found = true
			if p.Flags&elf.PF_X == 0 {
				must(fmt.Errorf("code segment not executable"))
			}
		}
	}
	if !found {
		must(fmt.Errorf("kpj_code not inside a file-backed load segment"))
	}
	f.Close()
	must(exec.Command("strip", "-o", "runtime.elf", "runtime_unstripped.elf").Run())
	os.Remove("runtime_unstripped.elf")

	names := make([]string, 0, len(addrs))
	for n := range addrs {
		names = append(names, n)
	}
	sort.Strings(names)
	var sb strings.Builder
	sb.WriteString("// Code generated by gen_runtime.go; DO NOT EDIT.\n\npackage main\n\n")
	fmt.Fprintf(&sb, "const rtCodeVaddr = 0x%x\nconst rtCodeFileOff = 0x%x\nconst rtCodeSize = 262144\n\n", code, off)
	sb.WriteString("var rtSyms = map[string]uint64{\n")
	for _, n := range names {
		fmt.Fprintf(&sb, "\t%q: 0x%x,\n", n, addrs[n])
	}
	sb.WriteString("}\n")
	must(os.WriteFile("rtaddrs_gen.go", []byte(sb.String()), 0644))

	// Embed the ELF as a Go string literal so only *.go files are needed to build.
	elfBytes, err := os.ReadFile("runtime.elf")
	must(err)
	var eb strings.Builder
	eb.WriteString("// Code generated by gen_runtime.go; DO NOT EDIT.\n\npackage main\n\nconst runtimeELFData = \"")
	const hexd = "0123456789abcdef"
	for _, c := range elfBytes {
		eb.WriteString("\\x")
		eb.WriteByte(hexd[c>>4])
		eb.WriteByte(hexd[c&15])
	}
	eb.WriteString("\"\n")
	must(os.WriteFile("rtdata_gen.go", []byte(eb.String()), 0644))
	os.Remove("runtime.elf")
}
